#!/usr/bin/env python3
"""Muse LLM Bridge: an OpenAI-compatible endpoint whose "model" is the
MCP host agent itself (Muse / Lev).

How it works:
  - MiroFish (or any OpenAI-compatible client) POSTs to /v1/chat/completions.
  - The bridge queues the request instead of calling a model API.
  - The host agent polls the queue (directly or via the MiroFish MCP server
    tools `pending_llm_requests` / `answer_llm_request`), generates the
    completions itself, and submits them back.
  - The bridge returns the agent's text as a standard chat completion.

This makes the host agent the literal inference engine of the simulation:
every ontology, persona, agent action, and report paragraph is generated by
the agent driving the MCP tools.

Config (environment):
  BRIDGE_PORT            listen port (default 8791)
  BRIDGE_TIMEOUT_SECONDS max wait per request before 504 (default 1800)
  BRIDGE_MODEL_NAME      model name to advertise (default "muse-spark")
  BRIDGE_LOG             JSONL audit log path (default ./requests.log.jsonl)

Notes:
  - Non-streaming only. A request with stream=true gets a 400 explaining why.
  - Answers may include native tool_calls: POST /bridge/respond accepts
    {"request_id": ..., "content": "...", "tool_calls": [...]}.
  - State is in-memory; restarting the bridge drops pending requests
    (clients with retry logic will simply re-ask).
"""

import hashlib
import json
import os
import threading
import time
import uuid

from flask import Flask, jsonify, request

PORT = int(os.environ.get("BRIDGE_PORT", "8791"))
TIMEOUT = float(os.environ.get("BRIDGE_TIMEOUT_SECONDS", "1800"))
MODEL_NAME = os.environ.get("BRIDGE_MODEL_NAME", "muse-spark")
LOG_PATH = os.environ.get("BRIDGE_LOG", os.path.join(os.path.dirname(__file__), "requests.log.jsonl"))
CACHE_PATH = os.environ.get("BRIDGE_CACHE", os.path.join(os.path.dirname(__file__), "response_cache.json"))
CACHE_ENABLED = os.environ.get("BRIDGE_CACHE_ENABLED", "1") == "1"

app = Flask(__name__)

_lock = threading.Lock()
_pending: dict[str, dict] = {}   # request_id -> record (with threading.Event)
_stats = {"received": 0, "answered": 0, "timed_out": 0, "cache_hits": 0}

# ------------------------------------------------------------ response cache
# Exact-repeat requests (client retries after timeouts, duplicate agent
# prompts) are answered instantly from the cache instead of queueing for the
# host agent again. Keyed on the full request payload, persisted to disk.

def _cache_key(body: dict) -> str:
    canonical = json.dumps({
        "model": body.get("model"),
        "messages": body.get("messages"),
        "response_format": body.get("response_format"),
        "tools": body.get("tools"),
        "tool_choice": body.get("tool_choice"),
    }, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _cache_load() -> dict:
    if not CACHE_ENABLED:
        return {}
    try:
        with open(CACHE_PATH, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def _cache_store(cache: dict) -> None:
    if not CACHE_ENABLED:
        return
    try:
        tmp = CACHE_PATH + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False)
        os.replace(tmp, CACHE_PATH)
    except OSError:
        pass


_cache = _cache_load()


def _classify(messages) -> str:
    """Rough kind of a queued request, so the host agent can dispatch
    answerer subagents by category (extraction vs personas vs actions...)."""
    text = _preview(messages, 2000).lower()
    if "ontology" in text or "entity types" in text:
        return "ontology"
    if "extract" in text and ("entities" in text or "relationships" in text):
        return "graph_extraction"
    if "persona" in text or "profile" in text and "agent" in text:
        return "persona"
    if "simulation config" in text or "simulation parameters" in text:
        return "sim_config"
    if "final answer" in text or "report" in text and "section" in text:
        return "report"
    if "interview" in text:
        return "interview"
    if any(a in text for a in ("create_post", "like_post", "do_nothing", "repost")):
        return "sim_action"
    return "other"


def _log(event: dict) -> None:
    try:
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(json.dumps(event, ensure_ascii=False) + "\n")
    except OSError:
        pass


def _preview(messages, limit=600) -> str:
    parts = []
    for m in messages or []:
        role = m.get("role", "?")
        content = m.get("content", "")
        if isinstance(content, list):
            content = " ".join(
                str(p.get("text", "")) for p in content if isinstance(p, dict)
            )
        parts.append(f"[{role}] {content}")
    return "\n".join(parts)[:limit]


def _completion_payload(rec_id: str, model: str, messages, ans: dict) -> dict:
    content = ans.get("content") or ""
    message = {"role": "assistant", "content": content}
    if ans.get("tool_calls"):
        message["tool_calls"] = ans["tool_calls"]
        if not content:
            message["content"] = None
    prompt_chars = sum(len(str(m.get("content", ""))) for m in messages or [])
    return {
        "id": "chatcmpl-" + rec_id,
        "object": "chat.completion",
        "created": int(time.time()),
        "model": model,
        "choices": [{
            "index": 0,
            "message": message,
            "finish_reason": "tool_calls" if ans.get("tool_calls") else "stop",
        }],
        "usage": {
            "prompt_tokens": max(1, prompt_chars // 4),
            "completion_tokens": max(1, len(content) // 4),
            "total_tokens": max(2, (prompt_chars + len(content)) // 4),
        },
    }


def _public_record(rec: dict) -> dict:
    return {
        "request_id": rec["id"],
        "kind": rec.get("kind", "other"),
        "created_at": rec["created_at"],
        "model": rec["model"],
        "messages": rec["messages"],
        "response_format": rec.get("response_format"),
        "tools": rec.get("tools"),
        "tool_choice": rec.get("tool_choice"),
        "temperature": rec.get("temperature"),
        "max_tokens": rec.get("max_tokens"),
        "preview": _preview(rec["messages"]),
    }


@app.get("/health")
def health():
    with _lock:
        pending = len(_pending)
    return jsonify({"status": "ok", "service": "muse-llm-bridge", "model": MODEL_NAME,
                    "pending": pending, "stats": dict(_stats)})


@app.get("/v1/models")
def models():
    return jsonify({
        "object": "list",
        "data": [{
            "id": MODEL_NAME,
            "object": "model",
            "created": 0,
            "owned_by": "muse-agent-bridge",
        }],
    })


@app.post("/v1/chat/completions")
def chat_completions():
    body = request.get_json(silent=True) or {}
    if body.get("stream"):
        return jsonify({"error": {
            "message": "muse-llm-bridge does not support streaming; set stream=false",
            "type": "invalid_request_error", "param": "stream",
        }}), 400

    cache_key = _cache_key(body)
    with _lock:
        cached = _cache.get(cache_key)
        if cached is not None:
            _stats["cache_hits"] += 1
    if cached is not None:
        return jsonify(_completion_payload("cache_" + cache_key[:16], body.get("model") or MODEL_NAME,
                                            body.get("messages") or [], cached))

    rec = {
        "id": "req_" + uuid.uuid4().hex[:16],
        "cache_key": cache_key,
        "kind": _classify(body.get("messages") or []),
        "created_at": time.time(),
        "model": body.get("model") or MODEL_NAME,
        "messages": body.get("messages") or [],
        "response_format": body.get("response_format"),
        "tools": body.get("tools"),
        "tool_choice": body.get("tool_choice"),
        "temperature": body.get("temperature"),
        "max_tokens": body.get("max_tokens") or body.get("max_completion_tokens"),
        "event": threading.Event(),
        "answer": None,
    }
    with _lock:
        _pending[rec["id"]] = rec
        _stats["received"] += 1
    _log({"ts": rec["created_at"], "type": "request", "request_id": rec["id"],
          "model": rec["model"], "preview": _preview(rec["messages"], 300)})

    answered = rec["event"].wait(timeout=TIMEOUT)
    with _lock:
        _pending.pop(rec["id"], None)
        if answered:
            _stats["answered"] += 1
        else:
            _stats["timed_out"] += 1
    if not answered:
        return jsonify({"error": {
            "message": f"host agent did not answer within {int(TIMEOUT)}s",
            "type": "timeout_error",
        }}), 504

    ans = rec["answer"] or {}
    with _lock:
        _cache[rec["cache_key"]] = ans
        _cache_store(_cache)
    completion = _completion_payload(rec["id"], rec["model"], rec["messages"], ans)
    _log({"ts": time.time(), "type": "answer", "request_id": rec["id"],
          "content_preview": (ans.get("content") or "")[:300]})
    return jsonify(completion)


@app.get("/bridge/pending")
def pending():
    with _lock:
        records = sorted(_pending.values(), key=lambda r: r["created_at"])
    limit = int(request.args.get("limit", "50"))
    full = request.args.get("full", "0") == "1"
    out = []
    for rec in records[:limit]:
        if full:
            out.append(_public_record(rec))
        else:
            out.append({
                "request_id": rec["id"],
                "kind": rec.get("kind", "other"),
                "created_at": rec["created_at"],
                "model": rec["model"],
                "message_count": len(rec["messages"]),
                "has_tools": bool(rec.get("tools")),
                "response_format": rec.get("response_format"),
                "preview": _preview(rec["messages"]),
            })
    return jsonify({"pending": out, "count": len(records)})


@app.get("/bridge/request/<request_id>")
def get_request(request_id):
    with _lock:
        rec = _pending.get(request_id)
    if rec is None:
        return jsonify({"error": "request not found or already answered"}), 404
    return jsonify(_public_record(rec))


@app.post("/bridge/respond")
def respond():
    body = request.get_json(silent=True) or {}
    request_id = body.get("request_id")
    with _lock:
        rec = _pending.get(request_id)
        if rec is None:
            return jsonify({"error": "request not found or already answered"}), 404
        rec["answer"] = {
            "content": body.get("content"),
            "tool_calls": body.get("tool_calls"),
        }
        rec["event"].set()
    return jsonify({"ok": True, "request_id": request_id})


@app.post("/bridge/respond_batch")
def respond_batch():
    body = request.get_json(silent=True) or {}
    answers = body.get("answers") or []
    done, missing = [], []
    for item in answers:
        rid = item.get("request_id")
        with _lock:
            rec = _pending.get(rid)
            if rec is None:
                missing.append(rid)
                continue
            rec["answer"] = {
                "content": item.get("content"),
                "tool_calls": item.get("tool_calls"),
            }
            rec["event"].set()
            done.append(rid)
    return jsonify({"ok": True, "answered": done, "missing": missing})


@app.get("/bridge/stats")
def stats():
    with _lock:
        return jsonify({"pending": len(_pending), "stats": dict(_stats),
                        "model": MODEL_NAME, "timeout_seconds": TIMEOUT})


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=PORT, threaded=True)
